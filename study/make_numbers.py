sys.path.insert(0, os.path.join(HERE, ".."))

from paperengine.provenance import NumberRegistry, load_runs  # noqa: E402


def _ci(d: dict, digits: int = 1) -> str:
    """A percentage with its cluster-bootstrap interval, as the paper prints it."""
    return (f"{d['point']:.{digits}f}\% [{d['lo']:.{digits}f}, {d['hi']:.{digits}f}]")


def _write_resolution_table(br: dict, path: str) -> None:
    """Emit the whole table environment, not just its rows.

    LaTeX does not reliably tolerate an include inside a tabular, so the
    generated fragment carries the environment with it and is included at the
    point where the table belongs.
    """
    # Every benchmark with thirty or more matched comparisons, largest split
    # first; an earlier version listed a hand-picked eight, which a reviewer
    # rightly called a selection.
    MIN_N = 30
    order = sorted((k for k, d in br["by_benchmark"].items() if d["n"] >= MIN_N),
                   key=lambda k: -br["by_benchmark"][k]["size"])
    rows = []
    for name in order:
        d = br["by_benchmark"][name]
        size = format(d["size"], ",").replace(",", "{,}")
        rows.append(name + " & " + size + " & " + str(d["n"]) + " & "
                    + f"{d['median_gap']:.1f}" + " & " + f"{d['median_resolution']:.1f}" + " & "
                    + str(d["pct_below_sig"]) + chr(92) + "% & "
                    + str(d["pct_below"]) + chr(92) + "%")
    caption = ("Reported gaps against what the benchmark can resolve, for every "
               "benchmark with thirty or more matched comparisons, treating the "
               "two systems as independent. Gap and resolution (the minimum "
               "detectable difference at 80\\% power) are medians in points at the "
               "comparison's own pooled accuracy; `Not significant' is the share "
               "of gaps below 1.96 standard errors of the difference, `Below "
               "resolution' the share below the 80\\%-power value. Neither is a "
               "function of split size alone: both depend on the gaps a field "
               "reports on that benchmark.")
    nl = chr(10)
    rowsep = " " + chr(92) * 2 + nl
    b = chr(92)
    out = [
        "% Generated by study/make_numbers.py -- do not edit by hand.",
        b + "begin{table}[t]",
        b + "centering",
        b + "caption{" + caption + "}",
        b + "label{tab:resolution}",
        b + "small",
        b + "setlength{" + b + "tabcolsep}{4pt}",
        b + "begin{tabular}{lrrrrrr}",
        b + "toprule",
        "Benchmark & Split & $n$ & Gap & Resolution & Not significant & Below resolution " + b * 2,
        b + "midrule",
        rowsep.join(rows) + " " + b * 2,
        b + "bottomrule",
        b + "end{tabular}",
        b + "end{table}",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(nl.join(out) + nl)


def _write_mde_table(rows: list, paired_rho: float, path: str) -> None:
    """The benchmark resolution reference, as a generated LaTeX table."""
    b = chr(92)
    nl = chr(10)
    body = []
    for r in rows:
        size = format(r["split_size"], ",").replace(",", "{,}")
        body.append(" & ".join([
            r["benchmark"], size,
            format(r["mde_at_50"], ".2f"), format(r["mde_at_70"], ".2f"),
            format(r["mde_at_90"], ".2f"), format(r["mde_at_70_paired"], ".2f"),
        ]))
    caption = ("Smallest difference in accuracy, in percentage points, that each "
               "benchmark can distinguish from zero at 80 per cent power. Columns "
               "give the independent reading at three accuracies and the paired "
               "reading at 70 per cent. A property of the benchmark, not of any "
               "paper.")
    out = [
        "% Generated by study/make_numbers.py -- do not edit by hand.",
        b + "begin{table}[t]",
        b + "centering",
        b + "small",
        b + "caption{" + caption + "}",
        b + "label{tab:mde}",
        b + "begin{tabular}{lrrrrr}",
        b + "toprule",
        ("Benchmark & Split & At 50\% & At 70\% & At 90\% & Paired, 70\% "
         + b * 2),
        b + "midrule",
        (" " + b * 2 + nl).join(body) + " " + b * 2,
        b + "bottomrule",
        b + "end{tabular}",
        b + "end{table}",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(nl.join(out) + nl)


def _write_topic_table(tb: dict, path: str) -> None:
    """The two headlines by coarse subfield, as a table environment."""
    b, nl = chr(92), chr(10)
    rows = []
    for name, d in tb.items():
        rows.append(f"{name.capitalize()} & {d['papers']} & {d['comparisons']} & "
                    f"{d['pct_neither']}{b}% & {d['pct_testable']}{b}% & {d['n_testable']} & "
                    f"{d['pct_fail']}{b}% " + b * 2)
    caption = ("Both headline figures by coarse subfield, assigned from the title by "
               "keyword in the order listed. The share without an error bar is a "
               "property of the subfield; the failure rate among what can be tested "
               "is not.")
    out = [
        "% Generated by study/make_numbers.py -- do not edit by hand.",
        b + "begin{table}[t]", b + "centering", b + "small",
        b + "setlength{" + b + "tabcolsep}{4pt}",
        b + "caption{" + caption + "}", b + "label{tab:topics}",
        b + "begin{tabular}{lrrrrrr}", b + "toprule",
        "Subfield & Papers & Comparisons & No error bar & Testable & $n$ & Not distinguishable " + b * 2,
        b + "midrule", nl.join(rows), b + "bottomrule", b + "end{tabular}", b + "end{table}", "",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(nl.join(out))


def build(both_years_path: str, crosscheck_path: str, out_path: str,
          bootstrap_path: str = "out/bootstrap_ci.json") -> dict:
    with open(both_years_path, encoding="utf-8") as fh:
        by = json.load(fh)
    y25, y24 = by["2025"], by["2024"]
    with open(bootstrap_path, encoding="utf-8") as fh:
        boot = json.load(fh)
    b25, b24 = boot["2025"], boot["2024"]

    reg = NumberRegistry()
    run = "survivability_both_years-7f18e22a"

    # Corpus
    reg.add("papers total", y24["papers"] + y25["papers"], provenance=run)
    reg.add("papers twenty five", y25["papers"], provenance=run)
    reg.add("papers twenty four", y24["papers"], provenance=run)
    reg.add("comparisons total", y24["comparisons"] + y25["comparisons"], provenance=run)
    reg.add("comparisons twenty five", y25["comparisons"], provenance=run)
    reg.add("comparisons twenty four", y24["comparisons"], provenance=run)

    # The headline, which is the same in both years
    reg.add("pct neither side", f"{y25['pct_neither']}\\%", provenance=run)
    reg.add("pct neither side twenty four", f"{y24['pct_neither']}\\%", provenance=run)
    reg.add("pct with error bar", f"{y25['pct_err']}\\%", provenance=run)
    reg.add("pct with error bar twenty four", f"{y24['pct_err']}\\%", provenance=run)
    reg.add("pct stating n", f"{y25['pct_n']}\\%", provenance=run)
    reg.add("pct stating n twenty four", f"{y24['pct_n']}\\%", provenance=run)
    reg.add("pct no n stated", f"{y25['pct_no_n']}\\%", provenance=run)
    reg.add("pct one side only", f"{y25['pct_one']}\\%", provenance=run)
    reg.add("pct testable", f"{y25['pct_testable']}\\%", provenance=run)
    reg.add("pct testable twenty four", f"{y24['pct_testable']}\\%", provenance=run)

    # Survival
    reg.add("n testable", y25["n_testable"], provenance=run)
    reg.add("n testable twenty four", y24["n_testable"], provenance=run)
    reg.add("papers contributing", y25["papers_testable"], provenance=run)
    reg.add("papers contributing twenty four", y24["papers_testable"], provenance=run)
    reg.add("pct fail", f"{y25['pct_fail']}\\%", provenance=run)
    reg.add("pct fail twenty four", f"{y24['pct_fail']}\\%", provenance=run)
    reg.add("pct fail holm", f"{y25['pct_fail_holm']}\\%", provenance=run)
    reg.add("pct fail holm twenty four", f"{y24['pct_fail_holm']}\\%", provenance=run)
    reg.add("gap failing", f"{y25['gap_fail']}\\%", provenance=run)
    reg.add("gap passing", f"{y25['gap_pass']}\\%", provenance=run)
    reg.add("gap failing twenty four", f"{y24['gap_fail']}\\%", provenance=run)
    reg.add("gap passing twenty four", f"{y24['gap_pass']}\\%", provenance=run)

    # How much multiplicity alone moves the verdict
    moved = round(y25["pct_fail_holm"] - y25["pct_fail"], 1)
    reg.add("pct moved by multiplicity", f"{moved}\\%", provenance=run)
    reg.add("one in n moved by multiplicity", int(round(100.0 / moved)) if moved else 0,
            provenance=run)

    # Our own uncertainty. A paper asking everyone else to print a dispersion
    # and a run count has no business printing point estimates of its own, and
    # three of four reviewers said so in the same words.
    bootrun = "survivability_both_years-7f18e22a (cluster bootstrap over papers)"
    reg.add("ci neither side", _ci(b25["pct_neither"]), provenance=bootrun)
    reg.add("ci neither side twenty four", _ci(b24["pct_neither"]), provenance=bootrun)
    reg.add("ci testable", _ci(b25["pct_testable"]), provenance=bootrun)
    reg.add("ci testable twenty four", _ci(b24["pct_testable"]), provenance=bootrun)
    reg.add("ci fail", _ci(b25["pct_fail"]), provenance=bootrun)
    reg.add("ci fail twenty four", _ci(b24["pct_fail"]), provenance=bootrun)
    reg.add("ci fail holm", _ci(b25["pct_fail_holm"]), provenance=bootrun)
    reg.add("ci fail holm twenty four", _ci(b24["pct_fail_holm"]), provenance=bootrun)
    reg.add("ci holm delta", _ci(b25["holm_delta"]), provenance=bootrun)
    d = b25["deff"]
    reg.add("icc", f"{d['icc']:.2f}", provenance=bootrun)
    reg.add("design effect", f"{d['design_effect']:.2f}", provenance=bootrun)
    reg.add("deff root", f"{d['design_effect'] ** 0.5:.1f}", provenance=bootrun)
    reg.add("boot replicates", b25["pct_fail"]["n_boot"], provenance=bootrun)
    reg.add("n effective", d["n_eff"], provenance=bootrun)
    reg.add("mean cluster", f"{d['mean_cluster']:.1f}", provenance=bootrun)

    # The 2024 column was printing an em-dash for a category whose value was
    # sitting in the analysis output all along, which led one reviewer to
    # conclude the two years had been processed by different pipelines.
    reg.add("pct no n stated twenty four", f"{y24['pct_no_n']}\%", provenance=run)

    # Sensitivity to the two conventions the pipeline had to choose. Both are
    # reported as ranges: giving one number for a quantity that depends on an
    # arbitrary reading is the failure this paper is about.
    with open("out/sensitivity_2025.json", encoding="utf-8") as fh:
        sens = json.load(fh)
    sc, eb, ct = sens["run_count_scope"], sens["error_bar_meaning"], sens["paper_level_crosstab"]
    sensrun = "sensitivity_2025-d5aee395"
    reg.add("strict testable", rf"{sc['strict']['pct_testable']}\%", provenance=sensrun)
    reg.add("strict fail", rf"{sc['strict']['pct_fail']}\%", provenance=sensrun)
    reg.add("strict fail holm", rf"{sc['strict']['pct_fail_holm']}\%", provenance=sensrun)
    reg.add("unlabelled as std", rf"{eb['read_as_std']['pct_fail']}\%", provenance=sensrun)
    reg.add("unlabelled as sem", rf"{eb['read_as_sem']['pct_fail']}\%", provenance=sensrun)
    reg.add("labelled only fail", rf"{eb['labelled_only']['pct_fail']}\%", provenance=sensrun)
    reg.add("n unlabelled", eb["n_unknown"], provenance=sensrun)
    reg.add("papers error bar and runs", ct["error_bar_and_run_count"], provenance=sensrun)
    reg.add("papers error bar only", ct["error_bar_only"], provenance=sensrun)
    reg.add("pct error bar papers stating runs",
            rf"{ct['pct_of_error_bar_papers_that_also_state_runs']}\%", provenance=sensrun)

    # Everything the adversarial review round asked for and the earlier draft
    # did not have: the funnel, the power audit, the correlation range, what the
    # bold cell actually marks, and the checklist comparison.
    def _j(name):
        with open(f"out/{name}.json", encoding="utf-8") as fh:
            return json.load(fh)

    fn, pw, bs, ck = _j("funnel"), _j("power_audit"), _j("bold_semantics"), _j("checklist")
    corr = _j("correlation_sensitivity")

    reg.add("tables detected", fn["tables_detected"], provenance="funnel")
    reg.add("tables no orientation", fn["tables_with_no_usable_orientation"], provenance="funnel")
    reg.add("candidate groups", fn["candidate_groups"], provenance="funnel")
    reg.add("tables yielding", fn["tables_yielding_at_least_one_comparison"], provenance="funnel")
    reg.add("pct groups usable", rf"{fn['pct_of_groups_usable']}\%", provenance="funnel")
    reg.add("pct caption uncertainty",
            rf"{fn['pct_of_empty_tables_with_caption_uncertainty']}\%", provenance="funnel")

    # The power level is a parameter of the analysis, not an illustration, so it
    # comes from the run record like everything else rather than the whitelist.
    reg.add("power level", rf"{int(pw['power'] * 100)}\%", provenance="power_audit_2025")
    # Section 6 no longer conditions on the paper's own dispersion (that was the
    # observed-power fallacy); the design-side version takes the run count from
    # the paper and the noise from everyone else.
    dm = _j("design_mde")
    drun = "design_mde_2025"
    reg.add("design mde n", dm["n"], provenance=drun)
    reg.add("design mde papers", dm["n_papers"], provenance=drun)
    reg.add("pct below design mde", rf"{dm['pct_below_design_mde']}\%", provenance=drun)
    reg.add("design mde no bars n", dm["n_no_bars"], provenance=drun)
    reg.add("pct below design mde no bars", rf"{dm['pct_below_design_mde_no_bars']}\%", provenance=drun)
    reg.add("design mde testable n", dm["n_testable"], provenance=drun)
    reg.add("pct below design mde testable", rf"{dm['pct_below_design_mde_testable']}\%", provenance=drun)
    reg.add("pct below own mde", rf"{dm['own_dispersion']['pct_underpowered']}\%", provenance=drun)
    reg.add("design median sd", f"{dm['median_external_sd_percent_scale']}", provenance=drun)
    reg.add("design median mde", f"{dm['median_mde_percent_scale']}", provenance=drun)
    reg.add("design pct benchmark sd", rf"{dm['pct_sd_from_benchmark']}\%", provenance=drun)
    reg.add("design median runs", f"{dm['median_runs']:g}", provenance=drun)
    reg.add("pct below alpha threshold", rf"{dm['pct_below_alpha_threshold']}\%", provenance=drun)
    reg.add("pct below alpha threshold no bars", rf"{dm['pct_below_alpha_threshold_no_bars']}\%",
            provenance=drun)
    reg.add("design n percent", dm["n_percent_scale"], provenance=drun)
    reg.add("design n unit", dm["n_unit_scale"], provenance=drun)
    reg.add("design below percent", rf"{dm['pct_below_design_mde_percent_scale']}\%", provenance=drun)
    reg.add("design below unit", rf"{dm['pct_below_design_mde_unit_scale']}\%", provenance=drun)
    reg.add("design below benchmark matched", rf"{dm['pct_below_design_mde_benchmark_matched']}\%",
            provenance=drun)
    reg.add("design median sd unit", f"{dm['median_external_sd_unit_scale']}", provenance=drun)
    reg.add("design excluded no n", dm["excluded"]["no_run_count"], provenance=drun)
    reg.add("design excluded scale", dm["excluded"]["outside_both_scales"] + dm["excluded"]["scales_differ"],
            provenance=drun)

    reg.add("pct bold not extremal", rf"{bs['pct_not_extremal']}\%", provenance="bold_semantics")

    reg.add("check yes", ck["answered_yes"], provenance="checklist_vs_tables")
    reg.add("check yes no table", ck["yes_but_no_table_error_bar"], provenance="checklist_vs_tables")
    reg.add("pct check yes no table",
            rf"{ck['pct_of_yes_with_no_table_error_bar']}\%", provenance="checklist_vs_tables")
    reg.add("check justified by figures", ck["of_those_justified_by_figures"],
            provenance="checklist_vs_tables")
    reg.add("check no but has bar", ck["no_but_table_has_error_bar"], provenance="checklist_vs_tables")
    agree = ck["yes_and_table_has_error_bar"]
    denom = agree + ck["no_but_table_has_error_bar"]
    reg.add("check precision", f"{agree} of {denom}", provenance="checklist_vs_tables")

    reg.add("fail rho half", rf"{corr['0.5']['pct_fail']}\%", provenance="correlation_sensitivity")
    reg.add("fail rho nine", rf"{corr['0.9']['pct_fail']}\%", provenance="correlation_sensitivity")
    # The correlations themselves are analysis parameters, so they come from the
    # run record too rather than being typed into the sentence that cites them.
    reg.add("rho half", "0.5", provenance="correlation_sensitivity")
    reg.add("rho nine", "0.9", provenance="correlation_sensitivity")

    # Checkability without error bars: how large a test set the reported gaps
    # would need, and how that compares to the benchmark actually named.
    bn = _j("binomial_check")
    binrun = "required_test_set_size-612527a6"
    reg.add("binom comparisons", bn["n_comparisons"], provenance=binrun)
    reg.add("binom base ratio", f"{bn['n_comparisons'] / y25['n_testable']:.1f}", provenance=binrun)
    reg.add("binom papers", bn["n_papers"], provenance=binrun)
    reg.add("binom median gap", f"{bn['median_gap_points']}", provenance=binrun)
    reg.add("binom median n", f"{bn['required_test_set_size']['median']:,}", provenance=binrun)
    reg.add("binom over gsm", rf"{bn['share_needing_more_than']['GSM8K (test) (1319)']}\%",
            provenance=binrun)
    reg.add("binom over mmlu", rf"{bn['share_needing_more_than']['MMLU (test) (14042)']}\%",
            provenance=binrun)
    reg.add("binom median n wide", f"{bn['wide']['required_test_set_size']['median']:,}",
            provenance=binrun)
    reg.add("binom named comparisons", bn["metric_named"]["n_comparisons"], provenance=binrun)
    reg.add("binom named papers", bn["metric_named"]["n_papers"], provenance=binrun)
    reg.add("binom named median gap", f"{bn['metric_named']['median_gap_points']}", provenance=binrun)
    reg.add("binom named median n", f"{bn['metric_named']['required_test_set_size']['median']:,}",
            provenance=binrun)
    reg.add("binom named over gsm",
            rf"{bn['metric_named']['share_needing_more_than']['GSM8K (test) (1319)']}\%",
            provenance=binrun)

    br = _j("benchmark_resolution")
    brun = "benchmark_resolution-70df59d3"
    reg.add("resolution comparisons", br["n_comparisons"], provenance=brun)
    cu = br["checkable_union"]
    reg.add("checkable item route", rf"{cu['pct_item_route']}\%", provenance=brun)
    reg.add("checkable union", rf"{cu['pct_union']}\%", provenance=brun)
    reg.add("checkable overlap", cu["overlap"], provenance=brun)
    reg.add("resolution papers", br["n_papers"], provenance=brun)
    reg.add("resolution median gap", f"{br['median_gap']}", provenance=brun)
    reg.add("resolution median res", f"{br['median_resolution']}", provenance=brun)
    reg.add("resolution pct below", rf"{br['pct_below_resolution']}\%", provenance=brun)
    reg.add("resolution pct below sig", rf"{br['pct_below_significance']}\%", provenance=brun)
    reg.add("resolution pct below sig rho half", rf"{br['correlation_sensitivity_significance']['0.5']}\%", provenance=brun)
    reg.add("resolution pct below sig rho nine", rf"{br['correlation_sensitivity_significance']['0.9']}\%", provenance=brun)
    reg.add("resolution median sig", f"{br['median_sig_threshold']:.2f}", provenance=brun)
    reg.add("resolution pct below rho nine",
            rf"{br['correlation_sensitivity']['0.9']}\%", provenance=brun)
    reg.add("resolution pct below rho half",
            rf"{br['correlation_sensitivity']['0.5']}\%", provenance=brun)
    reg.add("resolution pct below rho seven",
            rf"{br['correlation_sensitivity']['0.7']}\%", provenance=brun)
    _write_resolution_table(br, os.path.join(os.path.dirname(out_path),
                                             "resolution_table.tex"))

    # The benchmark resolution reference: a property of the benchmarks, usable
    # before an experiment rather than after it.
    mde = _j("benchmark_mde_table")
    mrun = "benchmark_mde_reference-3d9133cd"
    by_name = {r["benchmark"]: r for r in mde["rows"]}
    reg.add("aime items", by_name["AIME"]["split_size"], provenance=mrun)
    reg.add("aime mde", f"{by_name['AIME']['mde_at_70']:.0f}", provenance=mrun)
    reg.add("humaneval items", by_name["HumanEval"]["split_size"], provenance=mrun)
    reg.add("humaneval mde", f"{by_name['HumanEval']['mde_at_70']:.0f}", provenance=mrun)
    reg.add("five hundred mde", f"{by_name['MATH-500']['mde_at_70']:.0f}", provenance=mrun)
    reg.add("five hundred items", by_name["MATH-500"]["split_size"], provenance=mrun)
    reg.add("paired rho", f"{mde['paired_rho']}", provenance=mrun)
    _write_mde_table(mde["rows"], mde["paired_rho"],
                     os.path.join(os.path.dirname(out_path), "mde_table.tex"))

    ck2 = _j("checkability_span")
    reg.add("testable as sem", rf"{ck2['pct_every_bar_a_standard_error']}\%",
            provenance="checkability_span")
    reg.add("testable span factor", f"{ck2['span_factor']}", provenance="checkability_span")

    # Every row of the conventions table on a stated population, and the span
    # over the rows that share the full one.
    span = _j("headline_span")
    hs = span["rows"]
    reg.add("span low", rf"{span['span'][0]}\%", provenance="headline_span")
    reg.add("span high", rf"{span['span'][1]}\%", provenance="headline_span")
    reg.add("span n", span["n_full_population"], provenance="headline_span")
    reg.add("fail z", rf"{hs['z_two_sided']['pct_fail']}\%", provenance="headline_span")
    reg.add("fail z holm", rf"{hs['z_two_sided']['pct_fail_holm']}\%", provenance="headline_span")
    for key, name in (("as_reported", "as reported"), ("one_sided", "one sided"),
                      ("unlabelled_as_sem", "unlabelled as sem full"), ("rho_0.5", "rho half"),
                      ("rho_0.9", "rho nine"), ("labelled_only", "labelled only"),
                      ("caption_run_count_only", "strict")):
        reg.add(f"holm {name}", rf"{hs[key]['pct_fail_holm']}\%", provenance="headline_span")
    reg.add("fail one sided", rf"{hs['one_sided']['pct_fail']}\%", provenance="headline_span")
    reg.add("fail holm paper", rf"{hs['holm_family_paper']['pct_fail_holm']}\%", provenance="headline_span")
