"""Generate the supplement's tables from run records: every field of the
reference-set scoring, and the list of items where reader and parser
disagree, with the reader's note."""
import csv
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "study"))
from gold_set import _match, _num, _unclear  # noqa: E402

D = "paper/aamas"


def tex(s: str) -> str:
    s = re.sub(r"[^\x20-\x7e]", "", s)
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"),
                 ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("~", "\\~{}"), ("^", "\\^{}"), ("<", "$<$"), (">", "$>$")):
        s = s.replace(a, b)
    return s


def scores_table():
    g = json.load(open("out/aamas/gold_set.json", encoding="utf-8"))
    f = g["testable"]["fields"]
    rows = [("Results table", "results_table"), ("Bold cell, alone in its group", "bold_cell"),
            ("Orientation", "orientation"), ("Direction", "direction"),
            ("Winner's mean", "winner_mean"), ("Winner's bar", "winner_disp"),
            ("Runner-up's mean", "runner_mean"), ("Runner-up's bar", "runner_disp"),
            ("Kind of bar (SD/SE/CI/unlabelled)", "disp_type"), ("Kind of bar, as the test uses it", "disp_treatment"),
            ("Run count", "n_runs"), ("Run count, where the reader found one", "n_runs_when_reader_found_one"),
            ("Whole claim, fully readable items", "claim_and_values"),
            ("Whole claim, unreadable value not counted against", "claim_or_unreadable"),
            ("Runner-up carries a citation or marker", "rival_copied")]
    out = ["% generated by aamas/supplement_tables.py -- do not edit",
           "\\begin{table}[h]", "\\caption{Every field of the reference-set scoring, testable stratum: the reader's agreement with the parser, with Wilson 95\\% intervals.}",
           "\\small", "\\begin{tabular}{@{}lrr@{}}", "\\toprule", "Field & Agree & \\% [95\\% CI] \\\\", "\\midrule"]
    for label, k in rows:
        if k not in f:
            continue
        d = f[k]
        out.append(f"{label} & {d['correct']} of {d['n']} & {d['pct']}\\% [{d['ci'][0]}, {d['ci'][1]}] \\\\")
    v = g["testable"]["verdict_2x2"]
    out.append("\\midrule")
    out.append(f"Verdict, both fail & \\multicolumn{{2}}{{r}}{{{v['both_fail']}}} \\\\")
    out.append(f"Verdict, both survive & \\multicolumn{{2}}{{r}}{{{v['both_survive']}}} \\\\")
    out.append(f"Reader fails, parser survives & \\multicolumn{{2}}{{r}}{{{v['reader_fail_pipeline_survive']}}} \\\\")
    out.append(f"Parser fails, reader survives & \\multicolumn{{2}}{{r}}{{{v['pipeline_fail_reader_survive']}}} \\\\")
    nb = g["no_bar"]
    out.append("\\midrule")
    for label, k in (("No-bar stratum: results table", "results_table"), ("No-bar stratum: bold cell alone", "bold_cell"),
                     ("No-bar stratum: winner's mean", "winner_mean"), ("No-bar stratum: runner-up's mean", "runner_mean"),
                     ("No-bar stratum: no bar for either cell", "error_bar_truly_absent")):
        d = nb[k]
        out.append(f"{label} & {d['correct']} of {d['n']} & {d['pct']}\\% [{d['ci'][0]}, {d['ci'][1]}] \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    open(os.path.join(D, "scores_table.tex"), "w", encoding="utf-8").write("\n".join(out) + "\n")


def bugs():
    items = {it["id"]: it for it in json.load(open("audits/aamas_gold/items.json", encoding="utf-8"))}
    rows = {r["id"]: r for r in csv.DictReader(open("audits/aamas_gold/labels.csv", encoding="utf-8", newline=""))}
    vf = (("winner_mean", "winner"), ("winner_disp", "winner_dispersion"), ("runner_mean", "runner_up"), ("runner_disp", "runner_dispersion"))
    out = ["% generated by aamas/supplement_tables.py -- do not edit",
           "Every reference-set item on which the reader and the parser disagree on the claim, "
           "with the reader's note (abridged). Nothing here was fixed; the parser is the one that "
           "produced the paper's numbers. Items rendered without a box are listed first.",
           "\\begin{itemize}\\small"]
    unboxed = [i for i, it in items.items() if it.get("mark") is None]
    out.append(f"\\item \\textbf{{No box rendered}} (items {', '.join(unboxed)}): the parser holds two records "
               "for the table on the page and the kit looked up the cell in the wrong one; the reader's answers are void.")
    for i, r in sorted(rows.items()):
        it = items[i]
        if it.get("mark") is None or it["stratum"] != "testable":
            continue
        pl = it["pipeline"]
        bad = []
        if r["bold_ok"].lower().startswith("n"):
            bad.append("boxed cell not a single bold")
        for f_, k in vf:
            if not _unclear(r[f_]) and not _match(_num(r[f_]), pl[k]):
                bad.append(f"{f_.replace('_', ' ')}: reader {tex(r[f_])}, parser {pl[k]}")
        if bad:
            note = tex(r["note"][:260]).strip()
            out.append(f"\\item \\textbf{{Item {i}}}: {'; '.join(bad)}. \\emph{{{note}}}")
    for i, r in sorted(rows.items()):
        it = items[i]
        if it.get("mark") is None or it["stratum"] != "no_bar":
            continue
        pl = it["pipeline"]
        bad = []
        if r["bold_ok"].lower().startswith("n"):
            bad.append("boxed cell not a single bold")
        if r["error_bar_present"].lower().startswith("y"):
            bad.append("reader finds a bar")
        for f_, k in (("winner_mean", "winner"), ("runner_mean", "runner_up")):
            if not _unclear(r[f_]) and not _match(_num(r[f_]), pl[k]):
                bad.append(f"{f_.replace('_', ' ')}: reader {tex(r[f_])}, parser {pl[k]}")
        if bad:
            note = tex(r["note"][:260]).strip()
            out.append(f"\\item \\textbf{{Item {i}}} (no-bar stratum): {'; '.join(bad)}. \\emph{{{note}}}")
    out.append("\\end{itemize}")
    open(os.path.join(D, "bugs.tex"), "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    scores_table()
    bugs()
    print("wrote scores_table.tex and bugs.tex")
